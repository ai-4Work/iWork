HEADER_FILL = PatternFill("solid", fgColor="FF1F4E79")
DATA_FILL = PatternFill("solid", fgColor="FFF2F7FB")
THIN = Side(style="thin")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def apply_style(ws, num_data_rows: int) -> None:
    """复刻源表样式：表头深蓝白字、数据行浅蓝、细边框、列宽、行高、冻结表头。"""
    for idx, width in enumerate(COLUMN_WIDTHS, start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width

    for col in range(1, len(HEADERS) + 1):
        cell = ws.cell(row=1, column=col)
        cell.font = Font(name="宋体", size=11, bold=True, color="FFFFFFFF")
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[1].height = 26

    for row in range(2, num_data_rows + 2):
        for col in range(1, len(HEADERS) + 1):
            cell = ws.cell(row=row, column=col)
            cell.font = Font(
                name="Calibri",
                size=10,
                bold=(col == 1),
            )
            cell.fill = DATA_FILL
            cell.alignment = Alignment(
                horizontal="center" if col in CENTER_COLUMNS else "left",
                vertical="top",
                wrap_text=True,
            )
            cell.border = BORDER
        ws.row_dimensions[row].height = 60

    ws.freeze_panes = "A2"


def build(output_path: Path) -> None:
    wb = Workbook()
    wb.remove(wb.active)

    for sheet_name, rows in CASE_DATA.items():
        ws = wb.create_sheet(title=sheet_name)
        ws.append(HEADERS)
        for row in rows:
            # CASE_DATA 每行 10 列（第 8 列为「验收要点」），产出表只留「期望行为」，
            # 故把要点用换行折进期望，列序去掉原第 8 列。
            expect, extra = row[5], row[7]
            if extra:
                expect = f"{expect}\n{extra}"
            ws.append(row[:5] + [expect] + row[6:7] + row[8:])
        apply_style(ws, len(rows))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output_path)


def main() -> None:
    base = Path(__file__).resolve().parent.parent
    output_path = base / "docs" / "chapters" / OUTPUT_NAME
    build(output_path)

    total = sum(len(rows) for rows in CASE_DATA.values())
    print(f"written: {output_path}")
    for sheet_name, rows in CASE_DATA.items():
        print(f"  {sheet_name}: {len(rows)} 条")
    print(f"  total: {total} 条")


if __name__ == "__main__":
    main()
